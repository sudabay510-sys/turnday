"""Shared database helper for quiz-plan apps.

When DATABASE_URL is set, uses Postgres (Neon pooled URL recommended) and
isolates each app in a schema named after its slug (override with
DATABASE_SCHEMA). Otherwise falls back to a local SQLite file so tests and
offline work still run.

Usage (see /workspace/quiz-plans/DB-NOTES.md):

    from db import open_store

    store = open_store(slug="shelfspeak", root=Path("."), db_env="SHELFSPEAK_DB")
    store.init()  # idempotent CREATE SCHEMA / CREATE TABLE
    row = store.query("SELECT * FROM quiz_sessions WHERE session_key=?", (key,), one=True)
    store.execute("INSERT INTO leads(email, name) VALUES(?, ?)", (email, name))
"""
from __future__ import annotations

import os
import re
import sqlite3
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Iterator, Sequence

SCHEMA_RE = re.compile(r"^[a-z][a-z0-9_]{0,62}$")
TABLES = ("quiz_sessions", "leads")

SQLITE_DDL = """
CREATE TABLE IF NOT EXISTS quiz_sessions(
  id INTEGER PRIMARY KEY,
  session_key TEXT UNIQUE NOT NULL,
  answers_json TEXT NOT NULL DEFAULT '{}',
  plan_json TEXT,
  email TEXT,
  created TEXT DEFAULT CURRENT_TIMESTAMP,
  updated TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS leads(
  id INTEGER PRIMARY KEY,
  email TEXT NOT NULL,
  name TEXT,
  plan_tier TEXT,
  answers_json TEXT,
  plan_json TEXT,
  source TEXT DEFAULT 'founding',
  created TEXT DEFAULT CURRENT_TIMESTAMP
);
"""


def _safe_schema(name: str) -> str:
    schema = (name or "").strip().lower()
    if not SCHEMA_RE.fullmatch(schema):
        raise ValueError(
            f"Invalid DATABASE_SCHEMA / slug {name!r}. Use a lowercase letter "
            "followed by letters, digits, or underscores (max 63 chars)."
        )
    return schema


def _pg_ddl(schema: str) -> list[str]:
    schema = _safe_schema(schema)
    return [
        f"CREATE SCHEMA IF NOT EXISTS {schema}",
        f"""
CREATE TABLE IF NOT EXISTS {schema}.quiz_sessions(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_key TEXT UNIQUE NOT NULL,
  answers_json TEXT NOT NULL DEFAULT '{{}}',
  plan_json TEXT,
  email TEXT,
  created TEXT DEFAULT CURRENT_TIMESTAMP,
  updated TEXT DEFAULT CURRENT_TIMESTAMP
)
""".strip(),
        f"""
CREATE TABLE IF NOT EXISTS {schema}.leads(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  name TEXT,
  plan_tier TEXT,
  answers_json TEXT,
  plan_json TEXT,
  source TEXT DEFAULT 'founding',
  created TEXT DEFAULT CURRENT_TIMESTAMP
)
""".strip(),
        f"CREATE INDEX IF NOT EXISTS quiz_sessions_email_idx ON {schema}.quiz_sessions (email)",
        f"CREATE INDEX IF NOT EXISTS leads_email_idx ON {schema}.leads (email)",
        f"CREATE INDEX IF NOT EXISTS leads_created_idx ON {schema}.leads (created)",
    ]


def _qualify(sql: str, schema: str) -> str:
    """Qualify known table names so we never rely on search_path (PgBouncer-safe)."""
    for table in TABLES:
        sql = re.sub(rf"(?i)\b{table}\b", f"{schema}.{table}", sql)
    return sql


def _to_pg_placeholders(sql: str) -> str:
    return sql.replace("?", "%s")


class Store:
    """Tiny SQL helper that speaks SQLite or Postgres with `?` placeholders."""

    def __init__(
        self,
        *,
        slug: str,
        root: Path | str,
        db_env: str | None = None,
        database_url: str | None = None,
        schema: str | None = None,
        sqlite_path: str | None = None,
    ):
        self.slug = slug
        url = (database_url if database_url is not None else os.environ.get("DATABASE_URL", "")).strip()
        self.backend = "postgres" if url else "sqlite"
        self.url = url
        self.schema = _safe_schema(schema or os.environ.get("DATABASE_SCHEMA") or slug)
        if self.backend == "sqlite":
            path = (
                sqlite_path
                or os.environ.get("DATABASE_PATH")
                or (os.environ.get(db_env, "") if db_env else "")
                or str(Path(root) / f"{slug}.db")
            )
            self.sqlite_path = str(path)
            Path(self.sqlite_path).parent.mkdir(parents=True, exist_ok=True)
        else:
            self.sqlite_path = None
        self._initialized = False

    def init(self) -> None:
        """Create schema and tables if they do not exist. Safe to call often."""
        if self.backend == "sqlite":
            with sqlite3.connect(self.sqlite_path) as conn:
                conn.executescript(SQLITE_DDL)
                conn.commit()
        else:
            import psycopg

            with psycopg.connect(self.url, connect_timeout=15) as conn:
                with conn.cursor() as cur:
                    for stmt in _pg_ddl(self.schema):
                        cur.execute(stmt)
                conn.commit()
        self._initialized = True

    def ping(self) -> bool:
        if self.backend == "sqlite":
            with sqlite3.connect(self.sqlite_path) as conn:
                conn.execute("SELECT 1")
            return True
        import psycopg

        with psycopg.connect(self.url, connect_timeout=15) as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT 1")
        return True

    @contextmanager
    def connection(self) -> Iterator[Any]:
        if not self._initialized:
            self.init()
        if self.backend == "sqlite":
            conn = sqlite3.connect(self.sqlite_path)
            conn.row_factory = sqlite3.Row
            try:
                yield conn
            finally:
                conn.close()
        else:
            import psycopg
            from psycopg.rows import dict_row

            conn = psycopg.connect(self.url, row_factory=dict_row, connect_timeout=15)
            try:
                yield conn
            finally:
                conn.close()

    def connect(self):
        """Open a request-scoped connection. Caller must close it."""
        if not self._initialized:
            self.init()
        if self.backend == "sqlite":
            conn = sqlite3.connect(self.sqlite_path)
            conn.row_factory = sqlite3.Row
            return conn
        import psycopg
        from psycopg.rows import dict_row

        return psycopg.connect(self.url, row_factory=dict_row, connect_timeout=15)

    def _prepare(self, sql: str) -> str:
        if self.backend == "postgres":
            return _to_pg_placeholders(_qualify(sql, self.schema))
        return sql

    def query(
        self,
        sql: str,
        args: Sequence[Any] = (),
        one: bool = False,
        conn: Any | None = None,
    ):
        prepared = self._prepare(sql)

        def _run(c):
            cur = c.execute(prepared, tuple(args))
            rows = cur.fetchall()
            return (rows[0] if rows else None) if one else rows

        if conn is not None:
            return _run(conn)
        with self.connection() as c:
            return _run(c)

    def execute(self, sql: str, args: Sequence[Any] = (), conn: Any | None = None):
        prepared = self._prepare(sql)
        returning = self.backend == "postgres" and re.match(r"(?is)^\s*insert\b", sql) and "returning" not in sql.lower()

        def _run(c):
            if returning:
                cur = c.execute(prepared + " RETURNING id", tuple(args))
                row = cur.fetchone()
                if self.backend == "postgres":
                    c.commit()
                if row is None:
                    return None
                return row["id"] if not isinstance(row, tuple) else row[0]
            cur = c.execute(prepared, tuple(args))
            if self.backend == "postgres":
                c.commit()
            else:
                c.commit()
            return getattr(cur, "lastrowid", None)

        if conn is not None:
            return _run(conn)
        with self.connection() as c:
            return _run(c)


def open_store(
    slug: str,
    root: Path | str,
    db_env: str | None = None,
    **kwargs: Any,
) -> Store:
    return Store(slug=slug, root=root, db_env=db_env, **kwargs)
